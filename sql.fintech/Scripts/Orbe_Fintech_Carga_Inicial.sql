-- DASHBOARD: USUÁRIO, ÚLTIMA DESPESA E ÚLTIMO INVESTIMENTO
SELECT
    U.ID_USUARIO      "ID DO USUÁRIO (PK)",
    U.NM_USUARIO      "NOME",
    U.DS_EMAIL        "E-MAIL",
    D.ID_TRANSACAO    "ID DA ÚLTIMA DESPESA",
    D.DS_TRANSACAO    "ÚLTIMA DESPESA",
    D.VL_TRANSACAO    "VALOR DA ÚLTIMA DESPESA",
    D.DT_TRANSACAO    "DATA DA ÚLTIMA DESPESA",
    I.ID_INVESTIMENTO "ID DO ÚLTIMO INVESTIMENTO",
    I.NM_INVESTIMENTO "ÚLTIMO INVESTIMENTO",
    I.VL_INVESTIDO    "VALOR INVESTIDO",
    I.VL_ATUAL        "VALOR ATUAL",
    I.DT_INVESTIMENTO "DATA DO ÚLTIMO INVESTIMENTO"
FROM
    T_USUARIO U
    LEFT JOIN (
        SELECT
            ID_USUARIO,
            ID_TRANSACAO,
            DS_TRANSACAO,
            VL_TRANSACAO,
            DT_TRANSACAO
        FROM
            T_TRANSACAO
        WHERE
                ID_USUARIO = 1
            AND TP_MOVIMENTACAO = 'SAIDA'
        ORDER BY
            DT_TRANSACAO DESC,
            ID_TRANSACAO DESC
        FETCH FIRST 1 ROW ONLY
    )         D ON ( U.ID_USUARIO = D.ID_USUARIO )
    LEFT JOIN (
        SELECT
            ID_USUARIO,
            ID_INVESTIMENTO,
            NM_INVESTIMENTO,
            VL_INVESTIDO,
            VL_ATUAL,
            DT_INVESTIMENTO
        FROM
            T_INVESTIMENTO
        WHERE
            ID_USUARIO = 1
        ORDER BY
            DT_INVESTIMENTO DESC,
            ID_INVESTIMENTO DESC
        FETCH FIRST 1 ROW ONLY
    )         I ON ( U.ID_USUARIO = I.ID_USUARIO )
WHERE
    U.ID_USUARIO = 1;